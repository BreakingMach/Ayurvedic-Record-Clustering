#!/usr/bin/env python3
"""
Export benchmark JSON outputs and cohort data into public/data/ for the React UI (Rule R1).

Every metric displayed in the UI comes strictly from results/*.json produced by Python.
Cohort JSONs are exported directly from Dataset/tridosha.zip (real categorical data) and
Dataset/synthetic/synthetic_cases_default.csv (explicitly tagged SYNTHETIC/SIMULATED).
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List

import pandas as pd

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from ayur_bench.data import CANONICAL_CLASSES, load_tridosha_dataset
from ayur_bench.synth import NUMERIC_VITAL_COLS


def export_all() -> None:
    results_dir = REPO_ROOT / "results"
    out_dir = REPO_ROOT / "public" / "data"
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Copy Python-generated results/*.json verbatim into public/data/
    for name in ("real_data.json", "synthetic.json", "expert_review.json"):
        src = results_dir / name
        if not src.exists():
            raise FileNotFoundError(f"Missing required result JSON: {src}")
        shutil.copy2(src, out_dir / name)

    # 2. Export real Kaggle categorical dataset (compact columnar/record format for Retrieval Simulator)
    real_bundle = load_tridosha_dataset()
    X_real = real_bundle.X
    y_real = real_bundle.y
    cat_cols = list(real_bundle.categorical_cols)

    trait_summaries: List[Dict[str, Any]] = []
    for col in cat_cols:
        vc = X_real[col].astype(str).value_counts()
        trait_summaries.append(
            {
                "name": col,
                "modality": "Categorical",
                "n_levels": int(len(vc)),
                "missing_count": int(X_real[col].isna().sum()),
                "levels": [{"level": str(k), "count": int(v)} for k, v in vc.items()],
            }
        )

    real_records = []
    for i in range(len(X_real)):
        row = X_real.iloc[i]
        rec = {
            "row_idx": i,
            "case_id": f"REAL-{i + 1:04d}",
            "dataset_label": str(y_real.iloc[i]),
            "traits": [str(row[c]) for c in cat_cols],
        }
        real_records.append(rec)

    with open(out_dir / "real_cases.json", "w", encoding="utf-8") as fh:
        json.dump(
            {
                "data_origin": "REAL (Kaggle adityaprashantshirke/prakriti-updated)",
                "label_provenance": real_bundle.metadata["label_provenance"],
                "categorical_cols": cat_cols,
                "numeric_cols": [],
                "trait_summaries": trait_summaries,
                "records": real_records,
            },
            fh,
            separators=(",", ":"),
        )

    # 3. Export default SYNTHETIC cohort (Dataset/synthetic/synthetic_cases_default.csv)
    synth_csv = REPO_ROOT / "Dataset" / "synthetic" / "synthetic_cases_default.csv"
    if not synth_csv.exists():
        raise FileNotFoundError(f"Missing default synthetic cohort: {synth_csv}")
    df_s = pd.read_csv(synth_csv)

    num_stats = {}
    for col in NUMERIC_VITAL_COLS:
        vals = df_s[col].dropna().astype(float)
        num_stats[col] = {
            "min": float(vals.min()),
            "max": float(vals.max()),
            "range": float(vals.max() - vals.min()),
            "mean": float(vals.mean()),
            "std": float(vals.std(ddof=0)),
            "median": float(vals.median()),
        }

    synth_records = []
    for i in range(len(df_s)):
        row = df_s.iloc[i]
        synth_records.append(
            {
                "row_idx": i,
                "case_id": f"SYNTH-{i + 1:04d}",
                "latent_class": str(row["latent_class"]),
                "eval_label": str(row["eval_label"]),
                "numerics": [float(row[c]) for c in NUMERIC_VITAL_COLS],
                "traits": [str(row[c]) for c in cat_cols],
            }
        )

    with open(out_dir / "synthetic_cases_default.json", "w", encoding="utf-8") as fh:
        json.dump(
            {
                "data_origin": "SYNTHETIC/SIMULATED",
                "warning": (
                    "SYNTHETIC/SIMULATED cohort generated by ayur_bench.synth.generator. "
                    "latent_class is simulation ground truth by construction, not a practitioner label."
                ),
                "numeric_cols": list(NUMERIC_VITAL_COLS),
                "categorical_cols": cat_cols,
                "numeric_stats": num_stats,
                "records": synth_records,
            },
            fh,
            separators=(",", ":"),
        )

    print(f"[UI Export] Wrote JSON assets to {out_dir}")


if __name__ == "__main__":
    export_all()
