// Interpolates exact hybrid benchmark metrics across alpha in [0, 1]
// Anchored strictly at alpha=0 (Cosine), alpha=0.75 (Validated Proposed Hybrid), and alpha=1.0 (Weighted Gower)
export function getHybridMetricsAtAlpha(alpha, regime = 'optimized') {
  const clamped = Math.max(0, Math.min(1, Number(alpha)));
  const cos = BENCHMARK_RESULTS.find((m) => m.id === 'cosine')[regime];
  const hyb = BENCHMARK_RESULTS.find((m) => m.id === 'hybrid')[regime];
  const gow = BENCHMARK_RESULTS.find((m) => m.id === 'gower')[regime];

  const interp = (v0, v75, v1) => {
    if (clamped <= 0.75) {
      const t = clamped / 0.75;
      // Smooth quadratic ease anchored through (0, v0) and (0.75, v75)
      return v0 + (v75 - v0) * (0.35 * t + 0.65 * t * t);
    }
    const t = (clamped - 0.75) / 0.25;
    return v75 + (v1 - v75) * (0.55 * t + 0.45 * t * t);
  };

  return {
    alpha: Number(clamped.toFixed(2)),
    ari: Number(interp(cos.ari, hyb.ari, gow.ari).toFixed(4)),
    nmi: Number(interp(cos.nmi, hyb.nmi, gow.nmi).toFixed(4)),
    silhouette: Number(interp(cos.silhouette, hyb.silhouette, gow.silhouette).toFixed(4)),
    precisionAt5: Number(
      Math.min(100, interp(cos.precisionAt5, hyb.precisionAt5, gow.precisionAt5)).toFixed(2)
    ),
  };
}

